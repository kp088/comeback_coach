import { Fragment } from "react";
import { cn } from "@/lib/utils";
import type { ContentSource } from "@/lib/coach";

/** Labels where content came from. "sample" = hand-written; "ai" = generated (future). */
export function SourceBadge({ source, className }: { source: ContentSource; className?: string }) {
  const sample = source === "sample";
  return (
    <span
      data-testid={`content-source-badge-${source}`}
      title={sample ? "Hand-written sample exercise bundled with the prototype" : "Generated by AI"}
      className={cn(
        "inline-flex items-center gap-1.5 rounded-full border px-2.5 py-0.5 text-xs font-medium",
        sample ? "border-sand-line bg-sand text-navy-muted" : "border-coral-line bg-coral-soft text-coral-ink",
        className,
      )}
    >
      <span className={cn("size-1.5 rounded-full", sample ? "bg-navy-muted" : "bg-coral")} />
      {sample ? "Sample content" : "AI-generated"}
    </span>
  );
}

export function ProgressBar({ value, max, testid }: { value: number; max: number; testid?: string }) {
  const pct = max === 0 ? 0 : Math.round((value / max) * 100);
  return (
    <div
      role="progressbar"
      aria-valuemin={0}
      aria-valuemax={max}
      aria-valuenow={value}
      data-testid={testid}
      className="h-2 w-full overflow-hidden rounded-full bg-sand"
    >
      <div className="h-full rounded-full bg-coral transition-[width] duration-500 ease-out" style={{ width: `${pct}%` }} />
    </div>
  );
}

/** Step dots: one per exercise in a goal. */
export function StepDots({ total, done }: { total: number; done: number }) {
  return (
    <div className="flex items-center gap-1.5" aria-hidden>
      {Array.from({ length: total }, (_, i) => (
        <span key={i} className={cn("h-1.5 w-6 rounded-full", i < done ? "bg-navy" : "bg-sand-line")} />
      ))}
    </div>
  );
}

/** Renders `backtick` segments as inline code. */
export function RichText({ text, className }: { text: string; className?: string }) {
  const parts = text.split("`");
  return (
    <span className={className}>
      {parts.map((p, i) =>
        i % 2 === 1 ? (
          <code key={i} className="rounded-md border border-sand-line bg-sand px-1.5 py-0.5 font-mono text-[0.85em] text-navy">
            {p}
          </code>
        ) : (
          <Fragment key={i}>{p}</Fragment>
        ),
      )}
    </span>
  );
}
